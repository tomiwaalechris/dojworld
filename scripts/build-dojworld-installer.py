"""Build a fresh, dedicated hotel installer; exclude all SaaS migrations."""
from pathlib import Path
import hashlib
import importlib.util

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('pms_installer', ROOT/'scripts/build-repeatable-installer.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
paths = sorted((ROOT/'supabase/migrations').glob('2026100*.sql'))
assert len(paths) == 19
core = '\n\n'.join('-- Source: '+p.name+'\n'+module.normalize(p) for p in paths)
booking = (ROOT/'supabase/dojworld/online-booking.sql').read_text()
def transaction_body(sql):
    # The installer and combined upgrade provide their own outer transaction.
    return '\n'.join(line for line in sql.splitlines() if line.strip().lower() not in {'begin;', 'commit;'})

additions = '\n\n'.join(transaction_body((ROOT/'supabase/dojworld'/name).read_text()) for name in [
    'front-desk-payments.sql', 'reservation-payment-summary.sql', 'channel-reservations.sql', 'booking-notifications.sql', 'booking-lifecycle.sql', 'booking-reconciliation.sql',
])
# Keep existing staff pricing and permissions, expiring old web holds under
# exactly the same room lock used by the original staff booking RPC.
original = (ROOT/'supabase/migrations/20261004000100_hotel_onboarding_and_stays.sql').read_text()
start = original.index('create or replace function public.create_reservation(')
end = original.index('create or replace function public.check_in_reservation', start)
forward = original[start:end].replace('  select r.housekeeping_status into v_room_status', '  perform booking_private.expire_room(p_room_id);\n  select r.housekeeping_status into v_room_status')
payload = core+'\n\n'+booking+'\n\n'+forward+'\n\n'+additions
checksum = hashlib.sha256(payload.encode()).hexdigest()
result = f'''-- GENERATED by scripts/build-dojworld-installer.py.
-- Fresh Dojworld project ONLY. No subscriptions, trial plans or platform admin.
-- Run the WHOLE file in Supabase SQL Editor as the project administrator.
-- This installer refuses an existing hotel project and preserves exact replays.
begin;
select pg_advisory_xact_lock(hashtextextended('dojworld:dedicated-install',0));
create table if not exists public.dojworld_install_release(checksum text primary key, installed_at timestamptz default now());
alter table public.dojworld_install_release enable row level security;
revoke all on public.dojworld_install_release from public,anon,authenticated;
do $doj_install$
begin
 if exists(select 1 from public.dojworld_install_release) then
   if exists(select 1 from public.dojworld_install_release where checksum='{checksum}') then return;end if;
   raise exception 'A different Dojworld release is installed. Use a reviewed upgrade, not the fresh installer.';
 end if;
 if to_regclass('public.organizations') is not null then
   raise exception 'This installer requires a fresh project. Existing hotel tables were found.';
 end if;
 execute $doj_payload${payload}$doj_payload$;
 insert into public.dojworld_install_release(checksum) values('{checksum}');
end $doj_install$;
commit;
'''
(ROOT/'supabase/dojworld-install.sql').write_text(result)
print('Generated supabase/dojworld-install.sql (19 core migrations + dedicated bookings and reception payments).')
upgrade_parts = ['fix-booking-settings.sql', 'bulk-online-rooms.sql', 'front-desk-payments.sql', 'reservation-payment-summary.sql', 'channel-reservations.sql', 'booking-notifications.sql', 'booking-lifecycle.sql', 'booking-reconciliation.sql']
upgrade = '''-- GENERATED by scripts/build-dojworld-installer.py.
-- Existing dedicated Dojworld project: run the WHOLE file in Supabase SQL Editor.
-- Adds channel inventory, booking recovery/email queues, hold expiry and payment/refund follow-up.
-- Preserves reservations, payments, policies, paused listings and booking switches.
begin;
select pg_advisory_xact_lock(hashtextextended('dojworld:booking-upgrade',0));
'''+ '\n\n'.join('-- Source: '+name+'\n'+transaction_body((ROOT/'supabase/dojworld'/name).read_text()) for name in upgrade_parts)+'''\n
notify pgrst,'reload schema';
commit;
'''
(ROOT/'supabase/dojworld-booking-upgrade.sql').write_text(upgrade)
print('Generated supabase/dojworld-booking-upgrade.sql (additive, repeatable existing-project update).')
